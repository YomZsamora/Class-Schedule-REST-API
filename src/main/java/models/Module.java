package models;

public class Module {
    private String name;
    private int id;

    public Module(String module_name) {
        this.name = name;
    }

    public String getModuleName() {
        return name;
    }

    public void setModuleName(String module_name) {
        this.name = name;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }
}
